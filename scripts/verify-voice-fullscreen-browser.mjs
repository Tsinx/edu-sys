import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.EDU_PLAYWRIGHT_PATH ? pathToFileURL(process.env.EDU_PLAYWRIGHT_PATH).href : 'playwright');
const origin = process.env.EDU_VOICE_QA_ORIGIN ?? 'http://127.0.0.1:5173';
const output = resolve('output/voice-fullscreen-review');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge', args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
page.setDefaultTimeout(30000);
const errors = [], uploads = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/**', route => { uploads.push(route.request().url()); return route.fulfill({ json: { text: '测试指令' } }); });
await page.route(`${origin}/voice-fullscreen-qa`, route => route.fulfill({ contentType: 'text/html', body: `<html><head><meta name="viewport" content="width=device-width,initial-scale=1"><script type="module">import RefreshRuntime from '/@react-refresh';RefreshRuntime.injectIntoGlobalHook(window);window.$RefreshReg$=()=>{};window.$RefreshSig$=()=>type=>type;window.__vite_plugin_react_preamble_installed__=true;</script><script type="module" src="/@vite/client"></script></head><body style="margin:0"><div id="root"></div><script type="module" src="/@fs/${resolve('apps/teacher-web/test/browser/voice-wake-harness.tsx').replaceAll('\\','/')}"></script></body></html>` }));
await page.addInitScript(() => {
  const audio = new AudioContext({ sampleRate: 16000 });
  const streams = [];
  Object.defineProperty(navigator.mediaDevices, 'getUserMedia', { value: async () => {
    await audio.resume();
    const destination = audio.createMediaStreamDestination();
    streams.push(destination.stream);
    return destination.stream;
  }});
  window.fullscreenQA = { count: () => streams.length, stopped: () => streams.every(stream => stream.getTracks().every(track => track.readyState === 'ended')) };
});
const button = name => page.getByRole('button', { name, exact: true });
const selected = async name => assert.equal(await button(name).getAttribute('aria-pressed'), 'true');
const enter = async () => { await button('进入全屏').click(); await page.waitForFunction(() => !!document.fullscreenElement); await button('退出全屏').waitFor(); };
const exit = async () => { await button('退出全屏').click(); await page.waitForFunction(() => !document.fullscreenElement); await button('进入全屏').waitFor(); };
const sameComposer = async () => assert.equal(await page.evaluate(() => window.originalComposer === document.querySelector('.teacher-command-composer')), true);
try {
  await page.goto(`${origin}/voice-fullscreen-qa`);
  await page.evaluate(() => { window.originalComposer = document.querySelector('.teacher-command-composer'); });
  await button('检测输入').click();
  await enter(); await selected('检测输入'); await sameComposer();
  await exit(); await selected('检测输入'); await sameComposer();
  checks.push('native fullscreen enter/exit preserves detected-input selection and DOM identity');
  await button('开启语音唤醒').click(); await page.getByText('等待唤醒', { exact: true }).waitFor();
  const count = await page.evaluate(() => window.fullscreenQA.count());
  await enter(); await page.getByText('等待唤醒', { exact: true }).waitFor();
  await exit(); await page.getByText('等待唤醒', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.fullscreenQA.count()), count);
  checks.push('active local detection keeps its existing microphone across fullscreen');
  await button('收起数字人').click();
  assert.equal(await page.evaluate(() => window.fullscreenQA.stopped()), false);
  await button('关闭语音唤醒').waitFor();
  await enter(); await selected('检测输入'); await sameComposer();
  await page.getByText('等待唤醒', { exact: true }).waitFor();
  await exit(); await button('展开数字人').click(); await selected('检测输入');
  checks.push('different normal/fullscreen collapse states keep the existing microphone and reachable off button');
  await enter(); await button('收起数字人').click();
  await button('关闭语音唤醒').click(); await page.waitForFunction(() => window.fullscreenQA.stopped());
  await button('开启语音唤醒').click(); await page.getByText('等待唤醒', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.fullscreenQA.stopped()), false);
  await page.screenshot({ path: resolve(output, 'fullscreen-mini-listening.png') });
  await exit(); await selected('检测输入');
  await enter(); await button('展开数字人').click(); await selected('检测输入'); await sameComposer(); await exit();
  checks.push('full-screen collapse then exit/reenter does not reset input mode');
  await button('文字输入').click();
  const input = page.getByRole('textbox', { name: '文字指令' });
  await input.fill('保留这段未发送的问题');
  await enter(); assert.equal(await input.inputValue(), '保留这段未发送的问题');
  await button('收起数字人').click(); await button('展开数字人').click();
  await exit(); await selected('文字输入'); assert.equal(await input.inputValue(), '保留这段未发送的问题');
  checks.push('text selection and unsent draft survive fullscreen and collapse');
  await button('按键输入').click(); await button('开始录音').click(); await button('结束并发送').waitFor();
  const recordingCount = await page.evaluate(() => window.fullscreenQA.count());
  await enter(); await button('结束并发送').waitFor(); await exit(); await button('结束并发送').waitFor();
  assert.equal(await page.evaluate(() => window.fullscreenQA.count()), recordingCount);
  await enter();
  await button('收起数字人').click();
  assert.equal(await page.evaluate(() => window.fullscreenQA.stopped()), false);
  await page.waitForTimeout(350);
  await button('结束并发送').click();
  await page.waitForFunction(() => window.fullscreenQA.stopped());
  await page.waitForFunction(() => document.querySelector('output')?.textContent?.includes('测试指令'));
  assert.equal(uploads.length, 2);
  await button('展开数字人').click(); await selected('按键输入'); await button('开始录音').waitFor(); await exit();
  checks.push('collapsed mini-window ends the existing recording and submits exactly once');
  await page.setViewportSize({ width: 390, height: 844 }); await button('检测输入').click();
  await enter(); await selected('检测输入'); await page.screenshot({ path: resolve(output, 'fullscreen-narrow.png') });
  await button('开启语音唤醒').click(); await page.getByText('等待唤醒', { exact: true }).waitFor();
  await button('收起数字人').click(); await button('关闭语音唤醒').click();
  await page.waitForFunction(() => window.fullscreenQA.stopped());
  await button('展开数字人').click();
  checks.push('390px mini-window microphone button stays visible and clickable');
  await exit(); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  checks.push('390px native fullscreen retains selection with no horizontal overflow');
  await page.evaluate(() => window.voiceHarness.setSession('new-session')); await selected('按键输入');
  checks.push('a different classroom still starts a fresh input session');
  assert.equal(uploads.length, 2); assert.deepEqual(errors, []);
  const result = { checks, errors, uploads };
  await writeFile(resolve(output, 'browser-report.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} catch (error) {
  console.error(JSON.stringify({ checks, errors, uploads, state: await page.locator('body').innerText() }, null, 2));
  throw error;
} finally { await browser.close(); }
