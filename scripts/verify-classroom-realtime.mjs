import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require=createRequire(process.env.EDU_PLAYWRIGHT_ENTRY || 'C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/entry.js');
const {chromium}=require('playwright');
const output=resolve('output/realtime-only-qa');await mkdir(output,{recursive:true});
const fixtures=JSON.parse(await readFile(resolve('output/realtime-voice-qa/fixtures.json'),'utf8'));
const fixture=fixtures.find(f=>f.name==='question-1');
const browser=await chromium.launch({headless:true,args:['--autoplay-policy=no-user-gesture-required','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream',`--use-file-for-fake-audio-capture=${resolve('output/realtime-voice-qa/question-1.wav')}`]});
const report={checks:[],errors:[],events:[],timing:[],requests:[]};let session;
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['microphone']});
  const response=await context.request.post('http://127.0.0.1:4300/api/courses/course-port-management-intro/class-sessions',{data:{}});assert.equal(response.status(),201);session=await response.json();
  const page=await context.newPage();
  await page.addInitScript(()=>{localStorage.setItem('edu-classroom-voice-path-v1','existing');window.voiceTimings=[];window.addEventListener('edu:voice-timing',e=>window.voiceTimings.push(e.detail));});
  page.on('pageerror',e=>report.errors.push(e.message));
  page.on('request',r=>{if(/\/(asr|tts|assistant\/turns)$/.test(r.url()))report.requests.push(r.url());});
  page.on('websocket',ws=>{if(ws.url().includes('/assistant/realtime'))ws.on('framereceived',({payload})=>{try{const e=JSON.parse(payload.toString());report.events.push(e.type==='audio.delta'?{type:e.type,turnId:e.turnId,bytes:e.audioBase64.length}:e);}catch{}});});
  await page.goto(`https://localhost/classroom/${session.id}`,{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'开始录音',exact:true}).waitFor({timeout:90000});
  assert.equal(await page.getByLabel('语音链路',{exact:true}).count(),0);
  for(let i=0;i<300&&!report.events.some(e=>e.type==='session.ready');i++)await page.waitForTimeout(100);
  assert.ok(report.events.some(e=>e.type==='session.ready'),'Realtime connection must become ready');
  report.checks.push('Realtime is the only voice path, ignores stale existing-path preferences and preconnects through Caddy');
  await page.getByRole('button',{name:'开始录音',exact:true}).click();
  await page.getByRole('button',{name:'结束并发送',exact:true}).waitFor({timeout:30000});
  await page.waitForTimeout(fixture.durationMs+100);
  await page.getByRole('button',{name:'结束并发送',exact:true}).click();
  await page.waitForFunction(()=>window.voiceTimings.some(e=>e.event==='completed'),undefined,{timeout:120000});
  const change=await page.evaluate(async id=>{const r=await fetch(`/api/class-sessions/${id}/events`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({type:'next_slide'})});return r.status;},session.id);
  assert.equal(change,201);
  await page.getByRole('button',{name:'开始录音',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('button[aria-label="开始录音"]').disabled,undefined,{timeout:2000});
  report.checks.push('An external page change discards queued speech after generation completes and returns to idle within two seconds');
  report.timing=await page.evaluate(()=>window.voiceTimings);
  assert.ok(report.events.some(e=>e.type==='audio.delta'));
  assert.ok(report.events.some(e=>e.type==='dialogue.delta'));
  assert.ok(!report.events.some(e=>e.type==='error'),JSON.stringify(report.events.filter(e=>e.type==='error')));
  assert.equal(report.requests.length,0,'Realtime microphone must not call standalone ASR, assistant HTTP, or TTS');
  report.checks.push('Actual microphone button uploads audio, commits once, streams text/audio, and returns to idle without legacy calls');
  const sent=report.timing.find(e=>e.event==='commit'),audio=report.timing.find(e=>e.event==='first-audio');
  assert.ok(audio && sent);report.firstAudioMs=audio.at-sent.at;
  await page.screenshot({path:resolve(output,'classroom-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(1000);
  await page.screenshot({path:resolve(output,'classroom-narrow.png'),fullPage:true});
  report.checks.push('Desktop and narrow layout screenshots captured');
  await page.setViewportSize({width:1440,height:1000});
  if(await page.getByRole('button',{name:'展开小麦老师',exact:true}).isVisible())await page.getByRole('button',{name:'展开小麦老师',exact:true}).click();
  const readyCount=report.events.filter(e=>e.type==='session.ready').length;
  await page.reload({waitUntil:'domcontentloaded'});
  for(let i=0;i<300&&report.events.filter(e=>e.type==='session.ready').length===readyCount;i++)await page.waitForTimeout(100);
  assert.equal(report.events.filter(e=>e.type==='session.ready').length,readyCount+1);
  assert.equal(report.events.filter(e=>e.type==='turn.started').length,1,'reconnecting must not replay the previous recording');
  report.checks.push('Reload reconnects to the real upstream without replaying a turn');
  assert.deepEqual(report.errors,[]);
} catch(error) {report.failure=error.message;throw error;}
finally {
  await writeFile(resolve(output,'browser-report.json'),JSON.stringify(report,null,2));
  if(session)await fetch(`http://127.0.0.1:4300/api/class-sessions/${session.id}/end`,{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'}).then(r=>{if(!r.ok)throw new Error('Test classroom cleanup failed: '+r.status);});
  await browser.close();
  console.log(JSON.stringify({checks:report.checks,errors:report.errors,failure:report.failure,firstAudioMs:report.firstAudioMs}));
}
