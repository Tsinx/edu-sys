/** Formatting only: each question, option, explanation and page introduction above is authored. */
export function groupCheckPage(check: LimitGroupCheck): LimitPage {
  const [a,b]=check.questions;
  if(!a||!b||check.questions.length!==2) throw new Error('GROUP_CHECK_PAIR:'+check.id);
  return {
    title:check.pageTitle,kind:'exercise',visual:'comparison-board',layout:'table',style:'editorial',accent:'ink',
    sourceLabel:'概念模型',sourceNote:'小组练习 · 两题均为单选',conceptCheck:true,
    teachingCue:check.teachingCue,exerciseMinutes:check.minutes,exerciseActivityId:check.id,
    table:{columns:['① '+a.stem,'② '+b.stem],rows:[0,1,2,3].map(i=>[String.fromCharCode(65+i)+'. '+a.options![i],String.fromCharCode(65+i)+'. '+b.options![i]])},
    prompt:'先各自选择，再在小组内比较理由；讨论后各自提交两题答案。',
    steps:check.questions.map((q,i)=>({title:`第${i+1}题：${q.answer}`,text:q.explanation})),
    speech:[check.introduction+' 第一题，'+a.stem+' '+a.options!.map((s,i)=>String.fromCharCode(65+i)+'，'+s+'。').join('')+' 第二题，'+b.stem+' '+b.options!.map((s,i)=>String.fromCharCode(65+i)+'，'+s+'。').join('')+' 请先各自选择，再和同伴比较理由。',...check.questions.map((q,i)=>`第${i+1}题选${q.answer}。${q.explanation}`)]
  };
}
